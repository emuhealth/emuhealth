// Deterministic synthetic studies in the ClinicalTrials.gov API v2 shape. Nothing here is a real trial: ids use
// the NCT99 range, which ClinicalTrials.gov has not assigned, and sponsors, sites, and text are invented.

export type Study = Record<string, unknown>;

export interface GenerateOptions {
  /** Number of studies, 0 to 2000. Default 60. */
  studies?: number;
  /** PRNG seed. Default 1. */
  seed?: number;
}

const CONDITIONS = [
  { name: "Hypertension", keywords: ["blood pressure"], drug: "lisinopril" },
  { name: "Type 2 Diabetes", keywords: ["glycemic control", "HbA1c"], drug: "metformin" },
  { name: "Hyperlipidemia", keywords: ["cholesterol", "LDL"], drug: "atorvastatin" },
  { name: "Asthma", keywords: ["bronchodilator"], drug: "albuterol" },
  { name: "Gastroesophageal Reflux Disease", keywords: ["GERD", "heartburn"], drug: "omeprazole" },
  { name: "Generalized Anxiety Disorder", keywords: ["anxiety"], drug: "sertraline" },
  { name: "Obesity", keywords: ["weight loss", "BMI"], drug: "lifestyle program" },
];

export const STATUSES = [
  "RECRUITING",
  "NOT_YET_RECRUITING",
  "ACTIVE_NOT_RECRUITING",
  "COMPLETED",
  "TERMINATED",
  "WITHDRAWN",
  "ENROLLING_BY_INVITATION",
] as const;
const PHASES = [["EARLY_PHASE1"], ["PHASE1"], ["PHASE2"], ["PHASE3"], ["PHASE4"], ["PHASE1", "PHASE2"], ["NA"]];
const SPONSORS = [
  { name: "Synthetic Health Research Institute", class: "OTHER" },
  { name: "Example Pharmaceuticals Inc.", class: "INDUSTRY" },
  { name: "Placeholder University Medical Center", class: "OTHER" },
  { name: "Fictional Therapeutics LLC", class: "INDUSTRY" },
];
const SITES = [
  { facility: "Synthetic Health Clinic", city: "Springfield", state: "Illinois", zip: "62701" },
  { facility: "Riverton Example Hospital", city: "Riverton", state: "Wyoming", zip: "82501" },
  { facility: "Fairview Placeholder Medical Center", city: "Fairview", state: "Oregon", zip: "97024" },
  { facility: "Lakeside Synthetic Research Unit", city: "Lakeside", state: "California", zip: "92040" },
  { facility: "Greenville Example Clinic", city: "Greenville", state: "South Carolina", zip: "29601" },
];

function prng(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const DAY = 86_400_000;
const date = (ms: number) => new Date(ms).toISOString().slice(0, 10);
const month = (ms: number) => new Date(ms).toISOString().slice(0, 7);

export function generateStudies(options: GenerateOptions = {}): Study[] {
  const count = options.studies ?? 60;
  const seed = options.seed ?? 1;
  if (!Number.isInteger(count) || count < 0 || count > 2000)
    throw new Error("clinicaltrials.generate.studies must be an integer from 0 to 2000");
  if (!Number.isInteger(seed)) throw new Error("clinicaltrials.generate.seed must be an integer");
  const random = prng(seed);
  const int = (min: number, max: number) => min + Math.floor(random() * (max - min + 1));
  const pick = <T>(items: readonly T[]): T => items[Math.floor(random() * items.length)];
  const base = Date.parse("2021-01-01T00:00:00Z");

  const studies: Study[] = [];
  for (let n = 1; n <= count; n++) {
    const condition = CONDITIONS[(n - 1) % CONDITIONS.length];
    const status = pick(STATUSES);
    const phases = condition.drug === "lifestyle program" ? ["NA"] : pick(PHASES);
    const sponsor = pick(SPONSORS);
    const interventional = random() < 0.8;
    const start = base + int(0, 1700) * DAY;
    const completion = start + int(365, 1460) * DAY;
    const updated = Math.min(start + int(30, 900) * DAY, Date.parse("2026-01-01T00:00:00Z"));
    const enrollment = int(20, 1200);
    const sites = [...new Set([pick(SITES), pick(SITES)])];
    const nctId = `NCT99${String(n).padStart(6, "0")}`;
    const intervention = condition.drug === "lifestyle program" ? "Behavioral" : "Drug";
    const title = interventional
      ? `${condition.drug[0].toUpperCase()}${condition.drug.slice(1)} for ${condition.name} (Synthetic Study ${n})`
      : `Observational Registry of ${condition.name} (Synthetic Study ${n})`;
    studies.push({
      protocolSection: {
        identificationModule: {
          nctId,
          orgStudyIdInfo: { id: `SYN-${String(n).padStart(4, "0")}` },
          organization: { fullName: sponsor.name, class: sponsor.class },
          briefTitle: title,
          officialTitle: `${title}: a synthetic record generated by emuhealth for local development`,
        },
        statusModule: {
          statusVerifiedDate: month(updated),
          overallStatus: status,
          ...(status === "TERMINATED" || status === "WITHDRAWN"
            ? { whyStopped: "Synthetic record: stopped for illustration." }
            : {}),
          startDateStruct: { date: date(start), type: start > Date.parse("2026-01-01") ? "ESTIMATED" : "ACTUAL" },
          primaryCompletionDateStruct: { date: date(completion - 60 * DAY), type: "ESTIMATED" },
          completionDateStruct: { date: date(completion), type: "ESTIMATED" },
          studyFirstSubmitDate: date(start - 60 * DAY),
          studyFirstPostDateStruct: { date: date(start - 45 * DAY), type: "ACTUAL" },
          lastUpdatePostDateStruct: { date: date(updated), type: "ACTUAL" },
        },
        sponsorCollaboratorsModule: { leadSponsor: { name: sponsor.name, class: sponsor.class } },
        descriptionModule: {
          briefSummary: `Synthetic study for local development. It evaluates ${condition.drug} in adults with ${condition.name.toLowerCase()}. No real participants or results.`,
        },
        conditionsModule: { conditions: [condition.name], keywords: condition.keywords },
        designModule: {
          studyType: interventional ? "INTERVENTIONAL" : "OBSERVATIONAL",
          ...(interventional
            ? {
                phases,
                designInfo: {
                  allocation: "RANDOMIZED",
                  interventionModel: "PARALLEL",
                  primaryPurpose: "TREATMENT",
                  maskingInfo: { masking: pick(["NONE", "DOUBLE", "QUADRUPLE"]) },
                },
              }
            : { designInfo: { observationalModel: "COHORT", timePerspective: "PROSPECTIVE" } }),
          enrollmentInfo: { count: enrollment, type: status === "COMPLETED" ? "ACTUAL" : "ESTIMATED" },
        },
        armsInterventionsModule: {
          interventions: [
            {
              type: intervention.toUpperCase(),
              name: condition.drug,
              description: `Synthetic ${intervention.toLowerCase()} intervention.`,
            },
          ],
        },
        outcomesModule: {
          primaryOutcomes: [{ measure: `Change in ${condition.keywords[0]}`, timeFrame: "12 weeks" }],
        },
        eligibilityModule: {
          eligibilityCriteria: `Inclusion Criteria:\n\n* Adults with ${condition.name.toLowerCase()}\n\nExclusion Criteria:\n\n* Pregnancy`,
          healthyVolunteers: false,
          sex: "ALL",
          minimumAge: "18 Years",
          maximumAge: `${int(65, 85)} Years`,
          stdAges: ["ADULT", "OLDER_ADULT"],
        },
        contactsLocationsModule: {
          locations: sites.map((site) => ({
            ...site,
            country: "United States",
            ...(status === "RECRUITING" ? { status: "RECRUITING" } : {}),
          })),
        },
      },
      hasResults: false,
    });
  }
  return studies;
}
