/**
 * openFDA emulator: the drug label, adverse event, and enforcement (recall) endpoints of api.fda.gov, with the
 * openFDA query language, served from deterministic synthetic datasets. None of it is FDA data.
 */
export interface OpenFdaSeedConfig {
  port?: number;
  /** Generated datasets; false starts empty. */
  generate?: GenerateOptions | false;
  /** Extra synthetic records per endpoint, for example { "drug/label": [ ... ] }. */
  records?: Partial<Record<Endpoint, OpenFdaRecord[]>>;
}

const DATA_KEY = "openfda.datasets";
const SERVICE_LABEL = "openFDA";
const DOCS = "https://www.emuhealth.dev/docs/openfda";

function datasets(store: Store): Datasets {
  let data = store.getData<Datasets>(DATA_KEY);
  if (!data) {
    data = emptyDatasets();
    store.setData(DATA_KEY, data);
  }
  return data;
}

const emptyDatasets = (): Datasets =>
  Object.fromEntries(ENDPOINTS.map((e) => [e, [] as OpenFdaRecord[]])) as unknown as Datasets;

export function seedFromConfig(store: Store, _baseUrl: string, config: OpenFdaSeedConfig): void {
  if (config.generate !== undefined) {
    if (config.generate !== false && (typeof config.generate !== "object" || config.generate === null))
      throw new Error("openfda.generate must be an object of generator options or false");
    store.setData(DATA_KEY, config.generate === false ? emptyDatasets() : generateDatasets(config.generate));
  }
  if (config.records === undefined) return;
  if (typeof config.records !== "object" || config.records === null || Array.isArray(config.records))
    throw new Error("openfda.records must map endpoints such as drug/label to arrays of records");
  const data = datasets(store);
  for (const [endpoint, records] of Object.entries(config.records)) {
    if (!(ENDPOINTS as readonly string[]).includes(endpoint))
      throw new Error(`openfda.records: unknown endpoint ${endpoint}; use one of ${ENDPOINTS.join(", ")}`);
    if (!Array.isArray(records) || records.some((r) => !r || typeof r !== "object" || Array.isArray(r)))
      throw new Error(`openfda.records.${endpoint} must be an array of objects`);
    data[endpoint as Endpoint].push(...records);
  }
}

function meta(results?: { skip: number; limit: number; total: number }) {
  return {
    disclaimer:
      "Synthetic data generated by emuhealth for local development. It is not FDA data and must not be used for clinical decisions.",
    terms: DOCS,
    license: DOCS,
    last_updated: "2026-01-01",
    ...(results ? { results } : {}),
  };
}

function errorResponse(c: Context<AppEnv>, err: OpenFdaError): Response {
  return c.json({ error: { code: err.code, message: err.message } }, err.status as never);
}

function inspector(store: Store, active: string): string {
  const data = datasets(store);
  const tabs = ENDPOINTS.map((e) => ({ id: e, label: `${e} (${data[e].length})`, href: `/_inspector?tab=${e}` }));
  const endpoint = (ENDPOINTS as readonly string[]).includes(active) ? (active as Endpoint) : ENDPOINTS[0];
  const columns: Record<Endpoint, Array<[string, (r: OpenFdaRecord) => unknown]>> = {
    "drug/label": [
      ["id", (r) => r.id],
      ["generic name", (r) => (r.openfda as { generic_name?: string[] } | undefined)?.generic_name?.[0]],
      ["manufacturer", (r) => (r.openfda as { manufacturer_name?: string[] } | undefined)?.manufacturer_name?.[0]],
      ["effective", (r) => r.effective_time],
    ],
    "drug/event": [
      ["report", (r) => r.safetyreportid],
      ["received", (r) => r.receivedate],
      [
        "drug",
        (r) => (r.patient as { drug?: Array<{ medicinalproduct?: string }> } | undefined)?.drug?.[0]?.medicinalproduct,
      ],
      [
        "reactions",
        (r) =>
          (r.patient as { reaction?: Array<{ reactionmeddrapt?: string }> } | undefined)?.reaction
            ?.map((x) => x.reactionmeddrapt)
            .join(", "),
      ],
      ["serious", (r) => (r.serious === "1" ? "yes" : "no")],
    ],
    "drug/enforcement": recallColumns(),
    "device/enforcement": recallColumns(),
    "food/enforcement": recallColumns(),
  };
  const rows = data[endpoint]
    .slice(0, 100)
    .map(
      (record) =>
        `<tr>${columns[endpoint].map(([, get]) => `<td>${escapeHtml(String(get(record) ?? ""))}</td>`).join("")}</tr>`,
    );
  const head = columns[endpoint].map(([name]) => `<th>${escapeHtml(name)}</th>`).join("");
  const empty = `<tr><td colspan="${columns[endpoint].length}"><div class="inspector-empty">No records</div></td></tr>`;
  const query = `/${endpoint}.json?limit=5`;
  const body = `<div class="inspector-section"><h2>${escapeHtml(endpoint)}</h2>
<p>Query it at <a href="${escapeAttr(query)}">${escapeHtml(query)}</a>. Showing the first ${Math.min(100, data[endpoint].length)} of ${data[endpoint].length} synthetic records.</p>
<div class="inspector-scroll"><table class="inspector-table"><thead><tr>${head}</tr></thead><tbody>${rows.length ? rows.join("") : empty}</tbody></table></div></div>`;
  return renderInspectorPage("openFDA inspector", tabs, endpoint, body, SERVICE_LABEL);
}

function recallColumns(): Array<[string, (r: OpenFdaRecord) => unknown]> {
  return [
    ["recall", (r) => r.recall_number],
    ["classification", (r) => r.classification],
    ["status", (r) => r.status],
    ["product", (r) => r.product_description],
    ["reason", (r) => r.reason_for_recall],
  ];
}

export const openfdaPlugin: ServicePlugin = {
  name: "openfda",
  register(
    app: Hono<AppEnv>,
    store: Store,
    _webhooks: WebhookDispatcher,
    _baseUrl: string,
    _tokenMap?: TokenMap,
  ): void {
    for (const endpoint of ENDPOINTS) {
      app.get(`/${endpoint}.json`, (c) => {
        const params = new URL(c.req.url).searchParams;
        try {
          const records = datasets(store)[endpoint];
          if (params.get("count")) return c.json({ meta: meta(), results: runCount(records, params) });
          const result = runQuery(records, params);
          return c.json({
            meta: meta({ skip: result.skip, limit: result.limit, total: result.total }),
            results: result.results,
          });
        } catch (err) {
          if (err instanceof OpenFdaError) return errorResponse(c, err);
          throw err;
        }
      });
    }
    app.get("/_inspector", (c) => c.html(inspector(store, c.req.query("tab") ?? ENDPOINTS[0])));
    // Unknown endpoints answer the way openFDA does.
    app.get("/:rest{(?!_emulate).*}", (c) => errorResponse(c, new OpenFdaError(404, "NOT_FOUND", "No matches found!")));
  },
  seed(store: Store): void {
    store.setData(DATA_KEY, generateDatasets());
  },
};

export default openfdaPlugin;
